//! Bakes the configuration present at build time into the binary.
//!
//! A release build is run where the credentials are (a developer shell with direnv, or
//! CI with secrets), but it is used anywhere, so the values are captured here rather
//! than demanded again from every directory the agent is started in. Values are masked
//! (see src/obfuscate.rs) so the binary does not answer `strings`.
//!
//! A missing value fails the build rather than producing a binary that only works in
//! the tree it came from, since that failure would otherwise surface as a confusing
//! runtime error for whoever was given the binary. Builds that genuinely have no
//! credentials, CI in particular, set BUA_ALLOW_UNCONFIGURED_BUILD=1.

use std::env;
use std::fs;
use std::path::Path;

include!("src/env_var.rs");
include!("src/obfuscate.rs");

fn main() {
    println!("cargo:rerun-if-env-changed={ALLOW_UNCONFIGURED_BUILD}");
    let unconfigured_allowed = env::var(ALLOW_UNCONFIGURED_BUILD).as_deref() == Ok("1");

    let missing: Vec<&str> = REQUIRED
        .into_iter()
        .filter(|name| {
            env::var(name)
                .ok()
                .filter(|v| !v.trim().is_empty())
                .is_none()
        })
        .collect();

    if !missing.is_empty() && !unconfigured_allowed {
        for name in &missing {
            println!("cargo:warning={name} is not set");
        }
        panic!(
            "missing configuration: {}. Copy .envrc.example to .envrc and run `direnv allow`, \
             or set {ALLOW_UNCONFIGURED_BUILD}=1 to build a binary that must be configured \
             at run time.",
            missing.join(", ")
        );
    }

    let mut baked = String::from(
        "// Generated by build.rs. Masked; see src/obfuscate.rs.\n\
         pub(crate) const BAKED: &[(&str, &[u8])] = &[\n",
    );

    for name in ALL {
        // A rebuild is only needed when one of these changes, not on every touch of
        // the tree.
        println!("cargo:rerun-if-env-changed={name}");

        let Some(value) = env::var(name).ok().filter(|v| !v.trim().is_empty()) else {
            continue;
        };

        baked.push_str(&format!("    ({name:?}, &["));
        for byte in mask(value.as_bytes()) {
            baked.push_str(&format!("{byte},"));
        }
        baked.push_str("]),\n");
    }

    baked.push_str("];\n");

    let out = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("baked.rs");
    fs::write(&out, baked).expect("write the generated configuration");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/env_var.rs");
    println!("cargo:rerun-if-changed=src/obfuscate.rs");
}
