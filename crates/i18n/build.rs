//! Compiles `locales/*.ftl` into the Rust the crate exposes.
//!
//! Doing this at build time rather than at start is what makes a missing message or a misspelled
//! argument a compilation error instead of a string that reads wrong on somebody's screen. It also
//! means no catalog text is parsed while the agent is running: the running process holds finished
//! `&'static str`s and nothing that interprets them.
//!
//! `en-US` is the reference. It owns the set of messages and the name and kind of every argument,
//! so a translation can never change what a call site has to pass.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::Path;

include!("src/catalog.rs");
include!("src/plural.rs");

/// The locale every other one is checked against and falls back to.
const REFERENCE: &str = "en-US";

struct Locale {
    tag: String,
    language: String,
    variant: String,
    messages: BTreeMap<String, Message>,
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/catalog.rs");
    println!("cargo:rerun-if-changed=src/plural.rs");
    println!("cargo:rerun-if-changed=locales");

    let locales = load();
    let reference = locales
        .iter()
        .find(|l| l.tag == REFERENCE)
        .unwrap_or_else(|| {
            panic!("locales/{REFERENCE}.ftl is the reference catalog and must exist")
        });

    check(&locales, reference);

    let mut out = String::from("// Generated by build.rs from locales/*.ftl. Do not edit.\n");
    out.push_str(&locale_enum(&locales));
    out.push_str(&messages(&locales, reference));
    out.push_str(&macro_arms(reference));

    let path = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("messages.rs");
    fs::write(&path, out).expect("write the generated catalog");
}

/// Every catalog in `locales/`, reference first so generated indices are stable.
fn load() -> Vec<Locale> {
    let dir = Path::new("locales");
    let mut found: Vec<Locale> = Vec::new();

    let entries = fs::read_dir(dir).expect("locales/ exists");
    let mut paths: Vec<_> = entries
        .map(|e| e.expect("read locales/").path())
        .filter(|p| p.extension().is_some_and(|e| e == "ftl"))
        .collect();
    paths.sort();

    for path in paths {
        let tag = path
            .file_stem()
            .expect("a .ftl file has a stem")
            .to_str()
            .expect("locale filenames are ASCII")
            .to_string();
        let (language, region) = match tag.split_once('-') {
            Some((language, region)) => (language, Some(region)),
            None => (tag.as_str(), None),
        };
        let well_formed = language.len() >= 2
            && language.len() <= 3
            && language.chars().all(|c| c.is_ascii_lowercase())
            && region.is_none_or(|r| r.len() == 2 && r.chars().all(|c| c.is_ascii_uppercase()));
        assert!(
            well_formed,
            "locales/{tag}.ftl is not named for a locale: use `fr.ftl` or `fr-CA.ftl`"
        );

        let source = fs::read_to_string(&path).expect("read a catalog");
        let parsed = parse(&source).unwrap_or_else(|e| panic!("locales/{tag}.ftl: {e}"));

        let mut messages = BTreeMap::new();
        for message in parsed {
            messages.insert(message.id.clone(), message);
        }

        found.push(Locale {
            tag: tag.clone(),
            language: language.to_string(),
            variant: camel_case(&tag.to_lowercase()),
            messages,
        });
    }

    // The reference leads so `Locale as usize` indexes the per-message tables with the fallback
    // at a known position.
    found.sort_by_key(|l| (l.tag != REFERENCE, l.tag.clone()));
    found
}

/// Everything a translation is not allowed to do, checked before a line is generated.
fn check(locales: &[Locale], reference: &Locale) {
    for locale in locales {
        for (id, message) in &locale.messages {
            let Some(source) = reference.messages.get(id) else {
                panic!(
                    "locales/{}.ftl line {}: `{id}` is in no other catalog. A message is added to \
                     locales/{REFERENCE}.ftl first, so the call sites exist before a translation \
                     of them does",
                    locale.tag, message.line
                );
            };

            let expected = arguments(&source.value);
            for (name, selects) in arguments(&message.value) {
                let Some((_, source_selects)) = expected.iter().find(|(e, _)| *e == name) else {
                    panic!(
                        "locales/{}.ftl line {}: `{id}` reads `${name}`, which the message does \
                         not take",
                        locale.tag, message.line
                    );
                };
                assert!(
                    !selects || *source_selects,
                    "locales/{}.ftl line {}: `{id}` puts `${name}` in a plural select, but the \
                     message in locales/{REFERENCE}.ftl does not. The argument's Rust type comes \
                     from the reference, so give the reference the plural form first",
                    locale.tag,
                    message.line
                );
            }

            let has_select = matches!(message.value, Value::Select { .. });
            assert!(
                !has_select || is_known(&locale.language),
                "locales/{}.ftl line {}: `{id}` selects on a plural, and no plural rule for `{}` \
                 is written in crates/i18n/src/plural.rs. Add its rule there rather than letting \
                 it take English's",
                locale.tag,
                message.line,
                locale.language
            );
        }

        let missing = reference
            .messages
            .keys()
            .filter(|id| !locale.messages.contains_key(*id))
            .count();
        if missing > 0 && locale.tag != REFERENCE {
            println!(
                "cargo:warning=locales/{}.ftl is missing {missing} of {} messages, which will \
                 show in {REFERENCE}",
                locale.tag,
                reference.messages.len()
            );
        }
    }
}

fn locale_enum(locales: &[Locale]) -> String {
    let mut out = String::from(
        "\n/// A catalog that shipped with this build.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub enum Locale {\n",
    );
    for locale in locales {
        out.push_str(&format!(
            "    /// `{}`\n    {},\n",
            locale.tag, locale.variant
        ));
    }
    out.push_str("}\n\n");

    out.push_str("impl Locale {\n    /// The BCP-47 tag this catalog is named for.\n");
    out.push_str("    pub fn tag(self) -> &'static str {\n        match self {\n");
    for locale in locales {
        out.push_str(&format!(
            "            Locale::{} => {:?},\n",
            locale.variant, locale.tag
        ));
    }
    out.push_str("        }\n    }\n\n");

    out.push_str("    /// The language subtag, which is what plural rules are keyed on.\n");
    out.push_str("    pub fn language(self) -> &'static str {\n        match self {\n");
    for locale in locales {
        out.push_str(&format!(
            "            Locale::{} => {:?},\n",
            locale.variant, locale.language
        ));
    }
    out.push_str("        }\n    }\n}\n\n");

    out.push_str("/// Every catalog, reference first.\npub const LOCALES: &[Locale] = &[\n");
    for locale in locales {
        out.push_str(&format!("    Locale::{},\n", locale.variant));
    }
    out.push_str("];\n\n");

    out.push_str(&format!(
        "/// The catalog a request nothing else matches falls back to.\n\
         pub const DEFAULT: Locale = Locale::{};\n",
        locales[0].variant
    ));
    out
}

fn messages(locales: &[Locale], reference: &Locale) -> String {
    let mut out = String::new();
    for (id, source) in &reference.messages {
        let args = arguments(&source.value);
        let per_locale: Vec<&Message> = locales
            .iter()
            .map(|l| l.messages.get(id).unwrap_or(source))
            .collect();

        if args.is_empty() {
            out.push_str(&constant(id, locales, &per_locale));
        } else {
            out.push_str(&structure(id, locales, &per_locale, &args));
        }
    }
    out
}

/// A message with no arguments: one table, indexed by locale.
fn constant(id: &str, locales: &[Locale], per_locale: &[&Message]) -> String {
    let table = per_locale
        .iter()
        .map(|m| match &m.value {
            Value::Pattern(parts) => literal(parts),
            Value::Select { .. } => unreachable!("a select takes the argument it selects on"),
        })
        .collect::<Vec<_>>()
        .join(", ");

    format!(
        "\n#[allow(dead_code)]\npub fn {}() -> &'static str {{\n    \
         const TEXT: [&str; {}] = [{table}];\n    TEXT[crate::locale() as usize]\n}}\n",
        snake_case(id),
        locales.len()
    )
}

/// A message with arguments: a struct whose fields are those arguments, by name.
///
/// A struct rather than a function so the call site names what it passes, in any order, and so a
/// forgotten argument is a missing-field error naming the field rather than a count mismatch.
fn structure(
    id: &str,
    locales: &[Locale],
    per_locale: &[&Message],
    args: &[(String, bool)],
) -> String {
    let name = camel_case(id);
    let parameters = args
        .iter()
        .enumerate()
        .map(|(i, _)| format!("T{i}"))
        .collect::<Vec<_>>()
        .join(", ");
    let bounds = args
        .iter()
        .enumerate()
        .map(|(i, (_, selects))| {
            if *selects {
                format!("T{i}: Into<crate::Count>")
            } else {
                format!("T{i}: ::std::fmt::Display")
            }
        })
        .collect::<Vec<_>>()
        .join(", ");
    let fields = args
        .iter()
        .enumerate()
        .map(|(i, (arg, _))| format!("    pub {arg}: T{i},\n"))
        .collect::<String>();

    let mut out = format!(
        "\n#[allow(dead_code)]\npub struct {name}<{parameters}> {{\n{fields}}}\n\n\
         #[allow(dead_code)]\nimpl<{bounds}> {name}<{parameters}> {{\n    \
         // A locale that says the same thing without one of the arguments leaves it unread.\n    \
         #[allow(unused_variables)]\n    \
         pub fn render(self) -> String {{\n        let mut out = String::new();\n"
    );
    for (arg, selects) in args {
        if *selects {
            out.push_str(&format!(
                "        let {arg}: crate::Count = self.{arg}.into();\n"
            ));
        } else {
            out.push_str(&format!("        let {arg} = self.{arg};\n"));
        }
    }

    out.push_str("        match crate::locale() {\n");
    for (locale, message) in locales.iter().zip(per_locale) {
        out.push_str(&format!("            Locale::{} => {{\n", locale.variant));
        out.push_str(&render(&message.value, &locale.language, 16));
        out.push_str("            }\n");
    }
    out.push_str("        }\n        out\n    }\n}\n");
    out
}

/// The body that appends one locale's text to `out`.
fn render(value: &Value, language: &str, indent: usize) -> String {
    let pad = " ".repeat(indent);
    let Value::Select {
        arg,
        variants,
        default,
    } = value
    else {
        let Value::Pattern(parts) = value else {
            unreachable!("a value is a pattern or a select")
        };
        return append(parts, &pad);
    };

    let others: Vec<&Variant> = variants
        .iter()
        .enumerate()
        .filter(|(index, _)| index != default)
        .map(|(_, variant)| variant)
        .collect();

    // A select whose only variant is the default decides nothing, so it reads the count for
    // display and never asks which category it is in.
    if others.is_empty() {
        return append(&variants[*default].parts, &pad);
    }

    let mut out = String::new();
    if others.iter().any(|v| matches!(v.key, Key::Exact(_))) {
        out.push_str(&format!("{pad}let exact = {arg}.get();\n"));
    }
    if others.iter().any(|v| matches!(v.key, Key::Category(_))) {
        out.push_str(&format!(
            "{pad}let category = crate::plural::category({language:?}, {arg}.get());\n"
        ));
    }

    for (position, variant) in others.iter().enumerate() {
        let condition = match &variant.key {
            Key::Exact(n) => format!("exact == {n}"),
            Key::Category(c) => format!("category == {c:?}"),
        };
        let keyword = if position == 0 { "if" } else { "} else if" };
        out.push_str(&format!("{pad}{keyword} {condition} {{\n"));
        out.push_str(&append(&variant.parts, &format!("{pad}    ")));
    }
    out.push_str(&format!("{pad}}} else {{\n"));
    out.push_str(&append(&variants[*default].parts, &format!("{pad}    ")));
    out.push_str(&format!("{pad}}}\n"));
    out
}

fn append(parts: &[Part], pad: &str) -> String {
    let mut out = String::new();
    for part in parts {
        match part {
            // A one-character run becomes a `push`, because clippy is right that it should and
            // because clippy reads what is generated here as readily as what is written by hand.
            Part::Text(text) => {
                let mut chars = text.chars();
                match (chars.next(), chars.next()) {
                    (Some(only), None) => {
                        out.push_str(&format!("{pad}out.push({only:?});\n"));
                    }
                    _ => out.push_str(&format!("{pad}out.push_str({text:?});\n")),
                }
            }
            Part::Arg(name) => {
                out.push_str(&format!("{pad}out.push_str(&{name}.to_string());\n"));
            }
        }
    }
    out
}

/// One `t!` arm per message, which is what makes an unknown key fail to compile.
///
/// There is deliberately no arm taking a runtime key. A message chosen by a value rather than by
/// a name written in the source would be a decision, and content the agent was handed is exactly
/// what must never make one.
fn macro_arms(reference: &Locale) -> String {
    let mut out = String::from(
        "\n/// Look up a message by the name it has in the catalog.\n\
         ///\n\
         /// ```ignore\n\
         /// t!(confirm_write_title)\n\
         /// t!(status_turns, count = turns)\n\
         /// ```\n\
         #[macro_export]\nmacro_rules! t {\n",
    );
    for (id, message) in &reference.messages {
        let arm = snake_case(id);
        if arguments(&message.value).is_empty() {
            out.push_str(&format!(
                "    ({arm}) => {{ $crate::messages::{arm}() }};\n"
            ));
        } else {
            out.push_str(&format!(
                "    ({arm} $(, $field:ident = $value:expr)* $(,)?) => {{\n        \
                 $crate::messages::{} {{ $($field: $value),* }}.render()\n    }};\n",
                camel_case(id)
            ));
        }
    }
    out.push_str("}\n");
    out
}

/// A message with no arguments is one run of text, written back out as a Rust literal.
fn literal(parts: &[Part]) -> String {
    let text: String = parts
        .iter()
        .map(|part| match part {
            Part::Text(text) => text.as_str(),
            Part::Arg(_) => unreachable!("a message with an argument is not a constant"),
        })
        .collect();
    format!("{text:?}")
}
